"""Assemble the static build -- the same app, with Python running in the page.

There is no second implementation here. The bundle is the same ``web/`` front
end plus the ``multispy`` package itself, which Pyodide loads into the browser
and runs in-process. ``config.js`` is the only file that differs, and all it
says is which front end is behind the page.

    .venv\\Scripts\\python.exe tools\\build_static.py
    .venv\\Scripts\\python.exe tools\\build_static.py --serve 8800

``--serve`` runs the result locally, which is the only way to exercise the
static path without deploying it.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from multispy.docpage import DOCS, render_page  # noqa: E402

WEB_FILES = ("index.html", "app.js", "viewer3d.js", "backend.js")

SAMPLES_DIR = ROOT / "samples"
"""Ready-made project bundles to offer on the static build.

The local server lists whatever is in the projects folder, but a page served
from Pages has no disk and no projects folder, so without these a first visit
has nothing in it to look at. Each is a `.multispy.zip` exactly as "download"
produces, which means opening one goes through the same path as a bundle the
user brings themselves -- there is no second code path to keep working.
"""

PY_MODULES = (
    "__init__",
    "geometry",
    "mesh",
    "exif",
    "project",
    "solve",
    "export",
    "webapp",
)
"""The package as the browser needs it.

``__main__`` is a command line and ``server.py`` is the transport this build
replaces, so neither is shipped. ``docpage`` renders at build time instead.
"""

CONFIG_JS = """/* Generated by tools/build_static.py -- do not edit.
 *
 * This is the static build: there is no Python process behind the page, so the
 * page loads CPython itself and calls the same `multispy` package in-process.
 */
window.MULTISPY_MODE = 'pyodide';
window.MULTISPY_PY_BASE = 'py/';
"""

# The docs renderer writes absolute routes, which is right for the local server
# and wrong for a project page served from a subpath. Rewrite them to the flat
# files this build actually lays down.
DOC_LINK_REWRITES = {
    'href="/docs/tutorial"': 'href="tutorial.html"',
    'href="/docs/readme"': 'href="readme.html"',
    'href="/"': 'href="../index.html"',
}


def build(out_dir: Path) -> dict[str, int]:
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    written: dict[str, int] = {}

    def put(rel: str, data: bytes | str) -> None:
        target = out_dir / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(data, str):
            target.write_text(data, encoding="utf-8")
        else:
            target.write_bytes(data)
        written[rel] = target.stat().st_size

    for name in WEB_FILES:
        put(name, (ROOT / "web" / name).read_text(encoding="utf-8"))
    put("config.js", CONFIG_JS)

    for module in PY_MODULES:
        put(f"py/multispy/{module}.py", (ROOT / "multispy" / f"{module}.py").read_text("utf-8"))

    for route in DOCS:
        page = render_page(route)
        if page is None:
            continue
        for before, after in DOC_LINK_REWRITES.items():
            page = page.replace(before, after)
        put(f"docs/{route}.html", page)

    put("samples/index.json", json.dumps(copy_samples(put), indent=2))

    # Without this, Pages runs the tree through Jekyll, which drops every path
    # beginning with an underscore -- including py/multispy/__init__.py, so the
    # package would simply fail to import.
    put(".nojekyll", "")
    return written


def copy_samples(put) -> list[dict]:
    """Copy every sample bundle into the build and describe it for the menu.

    The description is read out of each zip rather than kept in a list here, so
    a sample cannot drift from its own manifest: drop a new `.multispy.zip` into
    `samples/` and it appears, with the right counts, next build. A bundle that
    will not open is skipped rather than shipped broken -- the menu offering a
    sample that fails on click is worse than the menu not offering it.
    """
    if not SAMPLES_DIR.is_dir():
        return []

    entries: list[dict] = []
    for path in sorted(SAMPLES_DIR.glob("*.multispy.zip")):
        try:
            with zipfile.ZipFile(path) as zf:
                project = json.loads(zf.read("project.multispy"))
                photos = sum(
                    1 for n in zf.namelist() if n.startswith("photos/") and not n.endswith("/")
                )
        except (OSError, KeyError, ValueError, zipfile.BadZipFile) as exc:
            print(f"  skipping {path.name}: {exc}", file=sys.stderr)
            continue

        rel = f"samples/{path.name}"
        put(rel, path.read_bytes())
        entries.append({
            "file": path.name,
            "name": project.get("name") or path.name.split(".")[0],
            "images": len(project.get("images", [])),
            "points": len(project.get("points", [])),
            "photos": photos,
            "bytes": path.stat().st_size,
        })
    return entries


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="dist", help="output folder (default: dist)")
    ap.add_argument("--serve", type=int, default=0, metavar="PORT",
                    help="serve the result locally to test the static path")
    args = ap.parse_args()

    out_dir = (ROOT / args.out).resolve()
    written = build(out_dir)

    total = sum(written.values())
    print(f"built {out_dir}  ({len(written)} files, {total / 1024:.0f} KB)")
    for rel in sorted(written):
        print(f"  {written[rel]:>8,}  {rel}")
    print(
        "\nPyodide, numpy, scipy and pillow come from the CDN at run time"
        " (~20 MB on first load, cached after)."
    )

    if args.serve:
        import http.server
        import socketserver

        class Handler(http.server.SimpleHTTPRequestHandler):
            def __init__(self, *a, **kw):
                super().__init__(*a, directory=str(out_dir), **kw)

            def log_message(self, fmt, *a):
                pass

        with socketserver.TCPServer(("127.0.0.1", args.serve), Handler) as httpd:
            print(f"\nserving {out_dir} at http://127.0.0.1:{args.serve}/  (ctrl+c to stop)")
            try:
                httpd.serve_forever()
            except KeyboardInterrupt:
                print("\nstopping")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
